export interface RefreshDeps {
  lint: () => FreshnessLintResult;
  regen: () => boolean;
  commit: () => "committed" | "nothing-to-commit" | "failed";
  log: (line: string) => void;
}

export interface RefreshResult {
  outcome:
    | "fresh"
    | "refreshed-committed"
    | "refreshed-nothing-to-commit"
    | "regen-failed"
    | "commit-failed"
    | "still-stale-after-regen";
  exitCode: 0 | 1;
  problemsBefore: string[];
  problemsAfter: string[];
}

/**
 * Decision core, unit-testable with injected deps: lint → (stale?) regen →
 * re-lint → commit. Identical semantics to the Task #4111 route-inventory
 * core. Never throws.
 */
export function refreshArtifactIfStale(spec: ArtifactSpec, deps: RefreshDeps): RefreshResult {
  const tag = `[generated-artifact-refresh:${spec.name}]`;
  const before = deps.lint();
  if (before.ok) {
    deps.log(`${tag} OK — committed artifact matches its inputs; nothing to do.`);
    return { outcome: "fresh", exitCode: 0, problemsBefore: [], problemsAfter: [] };
  }

  deps.log(`${tag} STALE after merge — ${before.problems.length} problem(s):`);
  for (const p of before.problems) deps.log(`  - ${p}`);
  deps.log(
    `${tag} auto-running \`${spec.regenCommand}\` (merge-shifted drift would otherwise turn every nightly run red until someone regenerates by hand) …`,
  );

  if (!deps.regen()) {
    deps.log(
      `${tag} !!! regen FAILED — artifact is still stale; the nightly lint WILL be red. Run \`${spec.regenCommand}\` by hand and commit ${spec.paths.join(" + ")}.`,
    );
    return {
      outcome: "regen-failed",
      exitCode: 1,
      problemsBefore: before.problems,
      problemsAfter: before.problems,
    };
  }

  const after = deps.lint();
  // Commit the refreshed artifacts regardless of remaining problems: a
  // regenerated artifact is accurate even when a source bug keeps the lint
  // red (regen cannot fix the source).
  const commitOutcome = deps.commit();
  if (commitOutcome === "failed") {
    deps.log(
      `${tag} !!! COMMIT FAILED — the regenerated artifact is only in the worktree. Commit ${spec.paths.join(" + ")} by hand or the refresh is lost on the next clean checkout.`,
    );
    return {
      outcome: "commit-failed",
      exitCode: 1,
      problemsBefore: before.problems,
      problemsAfter: after.problems,
    };
  }

  if (!after.ok) {
    deps.log(
      `${tag} !!! STILL FAILING after regen — ${after.problems.length} problem(s) regen cannot fix (fix the SOURCE):`,
    );
    for (const p of after.problems) deps.log(`  - ${p}`);
    return {
      outcome: "still-stale-after-regen",
      exitCode: 1,
      problemsBefore: before.problems,
      problemsAfter: after.problems,
    };
  }

  if (commitOutcome === "nothing-to-commit") {
    deps.log(
      `${tag} refreshed — artifact now fresh; files already matched HEAD, nothing to commit.`,
    );
    return {
      outcome: "refreshed-nothing-to-commit",
      exitCode: 0,
      problemsBefore: before.problems,
      problemsAfter: [],
    };
  }

  deps.log(`${tag} refreshed + committed — artifact fresh again. Nightly freshness lint stays green.`);
  return {
    outcome: "refreshed-committed",
    exitCode: 0,
    problemsBefore: before.problems,
    problemsAfter: [],
  };
}

function run(cmd: string, args: string[]): { ok: boolean; stderr: string } {
  try {
    const res = spawnSync(cmd, args, {
      encoding: "utf8",
      // The contract-table generator scans the whole client/tests corpus for
      // caller lists (~95s measured 2026-08-09); give real headroom.
      timeout: 300_000,
      maxBuffer: 32 * 1024 * 1024,
    });
    return { ok: res.status === 0, stderr: res.stderr ?? "" };
  } catch (err) {
    return { ok: false, stderr: (err as Error).message };
  }
}

function realRegen(spec: (typeof ARTIFACTS)[number]): boolean {
  const [cmd, ...args] = spec.regenArgv;
  const res = run(cmd, args);
  if (!res.ok) {
    console.error(
      `[generated-artifact-refresh:${spec.name}] regen stderr: ${res.stderr.trim().slice(0, 2000)}`,
    );
  }
  return res.ok;
}

function realCommit(spec: ArtifactSpec): "committed" | "nothing-to-commit" | "failed" {
  // Stage ONLY the artifact paths — post-merge worktrees can carry other
  // modifications that must never be swept into this auto-commit.
  const add = run("git", ["add", "--", ...spec.paths]);
  if (!add.ok) {
    console.error(`[generated-artifact-refresh:${spec.name}] git add failed: ${add.stderr.trim()}`);
    return "failed";
  }
  const staged = run("git", ["diff", "--cached", "--quiet", "--", ...spec.paths]);
  if (staged.ok) return "nothing-to-commit"; // exit 0 = no staged changes
  const commit = run("git", [
    "-c",
    "user.name=post-merge generated-artifact refresh",
    "-c",
    "user.email=post-merge@local",
    "commit",
    "--no-verify",
    "-m",
    spec.commitMessage,
    "--only",
    "--",
    ...spec.paths,
  ]);
  if (!commit.ok) {
    console.error(
      `[generated-artifact-refresh:${spec.name}] git commit failed: ${commit.stderr.trim()}`,
    );
    return "failed";
  }
  return "committed";
}

export function cliMain(): number {
  let exitCode = 0;
  for (const spec of ARTIFACTS) {
    const result = refreshArtifactIfStale(spec, {
      lint: spec.lint,
      regen: () => realRegen(spec),
      commit: () => realCommit(spec),
      log: (line) => console.log(line),
    });
    if (result.exitCode !== 0) exitCode = 1;
  }
  return exitCode;
}

const isMain =
  import.meta.url === `file://${process.argv[1]}` ||
  (process.argv[1]?.endsWith("post-merge-generated-artifact-refresh.ts") ?? false);
if (isMain) {
  process.exit(cliMain());
}
