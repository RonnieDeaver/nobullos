/** Minimal lint-result shape shared by every freshness lint we drive. */
export interface FreshnessLintResult {
  ok: boolean;
  problems: string[];
}

export interface ArtifactSpec {
  /** Short slug used in log lines. */
  name: string;
  /** Exact repo-relative paths staged + committed on refresh. */
  paths: readonly string[];
  /** Human-facing regen command, quoted in failure messages. */
  regenCommand: string;
  commitMessage: string;
}

/**
 * Task #4189 — freshness check for a governance inventory: the generators
 * have no separate lint module; `--check` IS `checkArtifact(committed,
 * generate())` (see scripts/governanceInventoryLib.ts runGeneratorCli), so we
 * call the exact same functions in-process rather than re-implementing the
 * comparison. A generate() throw (e.g. an orphaned override key — a source
 * problem regen cannot fix) is reported as a red result, which routes to the
 * loud-warn exit-1 path.
 */
function governanceLint(artifactPath: string, generate: () => InventoryDocument): FreshnessLintResult {
  try {
    return checkArtifact(artifactPath, generate());
  } catch (err) {
    return {
      ok: false,
      problems: [`generation failed: ${err instanceof Error ? err.message : String(err)}`],
    };
  }
}

