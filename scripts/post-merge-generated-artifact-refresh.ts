/**
 * Task #4115 — Post-merge auto-refresh for the REMAINING committed generated
 * artifacts with freshness lints (generalizing Task #4111's route-inventory
 * hook to the other two artifacts that can silently go stale after merges):
 *
 *   1. audits/D-endpoint-contract-table.{md,json}
 *      Generated FROM tests/route-inventory.json by
 *      scripts/generate-endpoint-contract-table.mjs. Merge-shifted drift is
 *      not just possible — the Task #4111 route-inventory auto-refresh
 *      CREATES it: when that hook regenerates the inventory (handler
 *      file:line moved), the contract table's handler column immediately
 *      goes stale, and lint-contract-table-freshness turns red on every
 *      nightly until someone regenerates by hand (exactly what happened
 *      twice on 2026-08-08). This hook therefore MUST run after the
 *      route-inventory refresh in scripts/post-merge.sh.
 *
 *   2. website/public (marketing bundle, stamped build-manifest.json)
 *      Generated by `npx tsx website/generate.ts`; the freshness lint
 *      compares a content fingerprint of the inputs against the committed
 *      stamp. Two tasks that each edit different website inputs and each
 *      regenerate can merge cleanly while neither side's stamp matches the
 *      UNION of inputs — silent post-merge staleness.
 *
 *   3. (Task #4189) The four generated governance inventories in
 *      audits/governance/ — data-ownership.json, integration-reliability.json,
 *      async-topology.json, test-portfolio-baseline.json — freshness-guarded
 *      by the tests/governance-*-inventory.test.ts smoke tests. Same
 *      parallel-merge failure mode as the route inventory: each branch fresh
 *      alone, stale after the merge union. Their `--check` is
 *      checkArtifact(committed, generate()) from governanceInventoryLib, so
 *      the hook drives those exact functions in-process (no re-implemented
 *      comparison). None of the four is generated from another artifact —
 *      no derived-artifact chaining.
 *
 * Same contract as scripts/post-merge-route-inventory-refresh.ts:
 *   - reuses each lint's exported runLint() (never re-implements the check);
 *   - on staleness runs the real generator, re-lints, and commits ONLY the
 *     artifact paths (`git add -- <paths>` + `git commit --only -- <paths>`,
 *     --no-verify, inline -c user.* identity);
 *   - a lint still red after regen commits the (accurate) regenerated
 *     artifacts anyway but exits 1 so post-merge.sh warns loudly;
 *   - exit 0 = all artifacts fresh or auto-refreshed clean; 1 = needs human
 *     attention. post-merge.sh treats failure as a loud non-fatal warning —
 *     the gate/nightly lints stay the authoritative enforcement.
 */

