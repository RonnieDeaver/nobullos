/**
 * Attachment upload thumbnail generation — POST /api/comms/channels/:id/messages/upload.
 *
 * tests/comms-attachment-serving.test.ts covers the GET serving side of
 * thumbnails (thumbnail_key lookup + ACL). This test covers the write side:
 * the upload route must generate a downscaled webp thumbnail for resizable
 * image types, persist thumbnail_key on the attachment row, and degrade
 * gracefully (thumbnail_key NULL, upload still succeeds) for non-image files
 * and for image payloads sharp cannot decode.
 *
 * Verifies:
 *   - Large PNG upload → two storage uploads (original + thumb/ webp), the
 *     thumbnail is a real webp downscaled to 600px wide, and the attachment
 *     row's thumbnail_key matches the uploaded thumb key
 *   - Small PNG (< 600px) → thumbnail generated without enlargement
 *   - Non-image (PDF) upload → single storage upload, thumbnail_key NULL
 *   - Corrupt bytes claiming image/png → upload still 201, thumbnail_key NULL
 *     (best-effort fallback, no 500)
 *   - Backfill (Task #3421): non-fast-list image/* rows are attempted (heic
 *     stamped, missing-original skipped with a logged reason) and the drain
 *     converges to zero pending
 *   - End-to-end serve: the thumbnail key produced by a real upload is served
 *     back via GET /api/comms/attachments/<thumbnailKey> to a channel member
 *     (200, webp, exact generated bytes), while a non-member gets 403
 *
 * Object storage is stubbed by patching ObjectStorageService.prototype, so no
 * real storage calls escape the test. sharp runs for real (it is the code
 * under test on the generation side and the decoder on the assertion side).
 */

